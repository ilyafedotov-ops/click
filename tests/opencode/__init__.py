"""Opencode testing framework for Click."""

# Test Categories:
# - Basic command tests: test_basic_commands.py
# - Option handling tests: test_options.py
# - Group/subcommand tests: test_groups.py
# - Error handling tests: test_errors.py
# - Integration tests: test_integration.py

# Naming Conventions:
# - Test files: test_<category>.py
# - Test classes: Test<FeatureName>
# - Test methods: test_<specific_behavior>[_when_<condition>]
# - Fixtures: <resource>_fixture
# - Markers: @pytest.mark.<category>

# Test Structure:
# Given: Setup and context
# When: Action or event
# Then: Expected outcome
